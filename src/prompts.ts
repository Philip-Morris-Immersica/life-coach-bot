export function buildContext(
  profile: Profile | undefined,
  habits: Habit[],
  insights: string[],
  reminders: Reminder[] = [],
  recentSummary?: string
): string {
  if (
    !profile &&
    habits.length === 0 &&
    insights.length === 0 &&
    reminders.length === 0
  )
    return "";
  const parts: string[] = ["--- КОНТЕКСТ ЗА ТОЗИ ЧОВЕК (от паметта) ---"];
  if (profile) {
    if (profile.focus) parts.push(`Фокус в момента: ${profile.focus}`);
    if (profile.identityCurrent)
      parts.push(`Текуща идентичност: ${profile.identityCurrent}`);
    if (profile.identityTarget)
      parts.push(`Целева идентичност: ${profile.identityTarget}`);
    if (profile.vision) parts.push(`Визия за желаното бъдеще: ${profile.vision}`);
    if (profile.beliefsLimiting)
      parts.push(`Ограничаващи вярвания: ${profile.beliefsLimiting}`);
    if (profile.beliefsNew) parts.push(`Нови вярвания: ${profile.beliefsNew}`);
    if (profile.story) parts.push(`Лична история: ${profile.story}`);
    if (profile.problems) parts.push(`Проблеми/съпротиви: ${profile.problems}`);
    if (profile.goals) parts.push(`Цели: ${profile.goals}`);
  }
  const building = habits.filter((h) => h.kind !== "limiting");
  const limiting = habits.filter((h) => h.kind === "limiting");
  if (building.length) {
    parts.push(
      "Навици за изграждане:\n" +
        building
          .map(
            (h) =>
              `- ${h.name} (${h.cadence})${h.identityLink ? ` → ${h.identityLink}` : ""}`
          )
          .join("\n")
    );
  }
  if (limiting.length) {
    parts.push(
      "Ограничаващи навици:\n" +
        limiting
          .map((h) => `- ${h.name}${h.trigger ? ` (тригер: ${h.trigger})` : ""}`)
          .join("\n")
    );
  }
  if (insights.length) {
    parts.push("Минали прозрения:\n" + insights.map((i) => `- ${i}`).join("\n"));
  }
  if (reminders.length) {
    parts.push(
      "Настроени напомняния:\n" +
        reminders
          .map(
            (r) => `- ${r.time}${r.reason ? ` (${r.reason})` : ""}`
          )
          .join("\n")
    );
  }
  if (recentSummary) parts.push(`Скорошен контекст: ${recentSummary}`);
  parts.push("--- КРАЙ НА КОНТЕКСТА ---");
  return parts.join("\n");
}

